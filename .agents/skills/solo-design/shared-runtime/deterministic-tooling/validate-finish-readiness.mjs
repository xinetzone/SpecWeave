#!/usr/bin/env node

/**
 * Validate Design artifact readiness after validate-design-workspace.mjs passed.
 *
 * This compatibility entrypoint intentionally keeps the historical file name.
 * The finish gate only checks engineering readiness for the Design canvas:
 * validation success, post-validation mutation, .design page/image registration,
 * page/asset file existence, interaction target integrity, and restore delivery
 * text policy when a final response draft is supplied.
 *
 * Usage:
 *   node validate-finish-readiness.mjs <design-project-path> [--check=all|mutation|readiness|artifact|repair-ledger|response] [--final-response-file=<draft.md>]
 */

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const SKILL_DIR = path.resolve(SCRIPT_DIR, '..', '..');
const SKILL_MANIFEST_PATH = path.join(SKILL_DIR, 'skill-release-manifest.json');
const HASH_IMAGE_EXTENSIONS = new Set(['.png', '.jpg', '.jpeg', '.gif', '.webp', '.svg']);
const MAX_PROJECT_HASH_ASSET_ENTRIES = 500;
const MAX_PROJECT_HASH_ASSET_DEPTH = 8;
const fileHashCache = new Map();
const SUMMARY_MUTABLE_FIELDS = new Set([
  'artifactReadinessEvidence',
  'finishReadinessEvidence',
  'validationHistory',
  'validationRepairLedger',
  'lastValidationReportCheckedAt',
  'validationSnapshot',
  'repairEntryEvidence',
  'repairStopConditionMet',
  'repairStopReason',
  'remainingBlockingIssues',
  'lastValidationReportPath',
]);

function parseArgs(argv) {
  const positional = [];
  const errors = [];
  const warnings = [];
  let check = 'all';
  let finalResponseFile = null;

  for (const arg of argv) {
    if (arg.startsWith('--final-response-file=')) {
      finalResponseFile = arg.slice('--final-response-file='.length);
    } else if (arg.startsWith('--check=')) {
      check = arg.slice('--check='.length);
    } else if (arg.startsWith('--')) {
      errors.push(`Unknown flag: ${arg}`);
    } else {
      positional.push(arg);
    }
  }

  if (!positional[0]) errors.push('Missing design project path');
  if (!['all', 'mutation', 'readiness', 'artifact', 'repair-ledger', 'response'].includes(check)) {
    errors.push(`Unsupported --check=${check}`);
  }

  return {
    designDir: positional[0] ? path.resolve(positional[0]) : null,
    check,
    finalResponseFile,
    errors,
    warnings,
  };
}

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function readSkillManifest() {
  try {
    return readJson(SKILL_MANIFEST_PATH);
  } catch {
    return null;
  }
}

function validationReportSkillVersion(report) {
  const provenance = report?.skillProvenance || {};
  return provenance.expected_version || provenance.version || null;
}

function validateReportSkillFreshness(report, errors) {
  const currentVersion = readSkillManifest()?.version || null;
  if (!currentVersion) return;
  const reportVersion = validationReportSkillVersion(report);
  if (!reportVersion) {
    errors.push('validation-report.json is missing skillProvenance.version; rerun validate-design-workspace.mjs with the current skill before finish readiness');
    return;
  }
  if (reportVersion !== currentVersion) {
    errors.push(`validation-report.json was generated by skill version ${reportVersion}, current skill version is ${currentVersion}; rerun validate-design-workspace.mjs before finish readiness`);
  }
}

function validateReportIntegrity(report, designDir, errors) {
  if (!report || typeof report !== 'object') return;
  if (String(report.terminalState || '').trim()) {
    errors.push(`validation-report.json terminalState=${report.terminalState}; stop and report blocking summary before finish readiness`);
  }
  if (!report.projectFileHashes || typeof report.projectFileHashes !== 'object' || Object.keys(report.projectFileHashes).length === 0) {
    errors.push('validation-report.json missing non-empty projectFileHashes');
  }
  if (!String(report.checkedAt || '').trim()) errors.push('validation-report.json missing checkedAt');
  if (!String(report.designDir || '').trim()) {
    errors.push('validation-report.json missing designDir');
  } else if (path.resolve(report.designDir) !== path.resolve(designDir)) {
    errors.push('validation-report.json designDir does not match current design project');
  }
  if (!Number.isInteger(report.renderBlockingErrorCount)) errors.push('validation-report.json missing renderBlockingErrorCount');
  if (!Number.isInteger(report.errorCount)) errors.push('validation-report.json missing errorCount');
  if (!report.validationRunDisciplineStatus || typeof report.validationRunDisciplineStatus !== 'object') {
    errors.push('validation-report.json missing validationRunDisciplineStatus');
  }
  if (!report.skillProvenance || typeof report.skillProvenance !== 'object') {
    errors.push('validation-report.json missing skillProvenance');
  }
}

function stableJson(value) {
  if (Array.isArray(value)) return `[${value.map(stableJson).join(',')}]`;
  if (value && typeof value === 'object') {
    return `{${Object.keys(value).sort().map(key => `${JSON.stringify(key)}:${stableJson(value[key])}`).join(',')}}`;
  }
  return JSON.stringify(value);
}

function hashString(value) {
  return crypto.createHash('sha256').update(String(value)).digest('hex');
}

function sha256File(filePath) {
  const stat = fs.statSync(filePath);
  const cacheKey = `${path.resolve(filePath)}:${stat.size}:${stat.mtimeMs}`;
  const cached = fileHashCache.get(cacheKey);
  if (typeof cached === 'string') return cached;
  const hash = crypto.createHash('sha256');
  const fd = fs.openSync(filePath, 'r');
  const buffer = Buffer.allocUnsafe(1024 * 1024);
  try {
    let bytesRead = 0;
    do {
      bytesRead = fs.readSync(fd, buffer, 0, buffer.length, null);
      if (bytesRead > 0) hash.update(buffer.subarray(0, bytesRead));
    } while (bytesRead > 0);
  } finally {
    fs.closeSync(fd);
  }
  const digest = hash.digest('hex');
  fileHashCache.set(cacheKey, digest);
  return digest;
}

async function sha256FileAsync(filePath) {
  const stat = fs.statSync(filePath);
  const cacheKey = `${path.resolve(filePath)}:${stat.size}:${stat.mtimeMs}`;
  const cached = fileHashCache.get(cacheKey);
  if (typeof cached === 'string') return cached;
  if (cached) return cached;

  const promise = (async () => {
    const hash = crypto.createHash('sha256');
    const handle = await fs.promises.open(filePath, 'r');
    const buffer = Buffer.allocUnsafe(1024 * 1024);
    try {
      let bytesRead = 0;
      do {
        ({ bytesRead } = await handle.read(buffer, 0, buffer.length, null));
        if (bytesRead > 0) hash.update(buffer.subarray(0, bytesRead));
      } while (bytesRead > 0);
    } finally {
      await handle.close();
    }
    return hash.digest('hex');
  })();

  fileHashCache.set(cacheKey, promise);
  const digest = await promise;
  fileHashCache.set(cacheKey, digest);
  return digest;
}

function resolveInsideDesignDir(designDir, relOrAbsPath, errors, label) {
  const trimmed = String(relOrAbsPath || '').trim();
  if (!trimmed) return null;
  const resolved = path.isAbsolute(trimmed) ? trimmed : path.resolve(designDir, trimmed);
  const root = path.resolve(designDir);
  if (!resolved.startsWith(`${root}${path.sep}`) && resolved !== root) {
    errors.push(`${label} escapes design project: ${trimmed}`);
    return null;
  }
  return resolved;
}

function normalizeSummaryForHash(summary) {
  if (!summary || typeof summary !== 'object') return summary;
  const cloned = JSON.parse(JSON.stringify(summary));
  if (cloned.project && typeof cloned.project === 'object') {
    for (const field of SUMMARY_MUTABLE_FIELDS) {
      delete cloned.project[field];
    }
  }
  return cloned;
}

function hashProjectFile(filePath, relPath) {
  if (relPath === 'runtime-orchestration-summary.json') {
    try {
      const summary = JSON.parse(fs.readFileSync(filePath, 'utf8'));
      return hashString(stableJson(normalizeSummaryForHash(summary)));
    } catch {
      return sha256File(filePath);
    }
  }
  return sha256File(filePath);
}

async function hashProjectFileAsync(filePath, relPath) {
  if (relPath === 'runtime-orchestration-summary.json') {
    try {
      const summary = JSON.parse(await fs.promises.readFile(filePath, 'utf8'));
      return hashString(stableJson(normalizeSummaryForHash(summary)));
    } catch {
      return sha256FileAsync(filePath);
    }
  }
  return sha256FileAsync(filePath);
}

async function mapLimit(items, limit, worker) {
  const results = new Array(items.length);
  let nextIndex = 0;
  async function runWorker() {
    while (nextIndex < items.length) {
      const currentIndex = nextIndex;
      nextIndex += 1;
      results[currentIndex] = await worker(items[currentIndex], currentIndex);
    }
  }
  const workers = Array.from({ length: Math.min(limit, items.length) }, () => runWorker());
  await Promise.all(workers);
  return results;
}

function createAssetTraversalState(warnings, label = 'project-hash') {
  return {
    count: 0,
    depthWarningEmitted: false,
    countWarningEmitted: false,
    warnings,
    label,
  };
}

function warnAssetTraversal(state, message) {
  if (!state?.warnings) return;
  state.warnings.push(`[${state.label}] ${message}`);
}

async function collectProjectFileHashes(designDir, warnings = null) {
  const relPaths = [];
  const assetState = createAssetTraversalState(warnings, 'project-hash');

  function addIfExists(relPath) {
    const filePath = path.join(designDir, relPath);
    if (fs.existsSync(filePath) && fs.statSync(filePath).isFile()) {
      relPaths.push(relPath.replace(/\\/g, '/'));
    }
  }

  for (const entry of fs.readdirSync(designDir, { withFileTypes: true })) {
    if (entry.isFile() && entry.name.endsWith('.design')) relPaths.push(entry.name);
  }
  addIfExists('colors_and_type.css');
  addIfExists('runtime-orchestration-summary.json');
  addIfExists('page-generation-summary.json');

  const pagesDir = path.join(designDir, 'pages');
  if (fs.existsSync(pagesDir)) {
    for (const entry of fs.readdirSync(pagesDir, { withFileTypes: true })) {
      if (entry.isFile() && entry.name.endsWith('.html')) {
        relPaths.push(path.posix.join('pages', entry.name));
      }
    }
  }

  function visitAssets(dir, prefix, depth = 0) {
    if (!fs.existsSync(dir)) return;
    if (depth > MAX_PROJECT_HASH_ASSET_DEPTH) {
      if (!assetState.depthWarningEmitted) {
        warnAssetTraversal(assetState, `assets/ traversal exceeded max depth ${MAX_PROJECT_HASH_ASSET_DEPTH}; deeper assets skipped`);
        assetState.depthWarningEmitted = true;
      }
      return;
    }
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const rel = path.join(prefix, entry.name);
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        visitAssets(full, rel, depth + 1);
      } else if (entry.isFile() && HASH_IMAGE_EXTENSIONS.has(path.extname(entry.name).toLowerCase())) {
        if (assetState.count >= MAX_PROJECT_HASH_ASSET_ENTRIES) {
          if (!assetState.countWarningEmitted) {
            warnAssetTraversal(assetState, `assets/ traversal reached max image count ${MAX_PROJECT_HASH_ASSET_ENTRIES}; remaining assets skipped`);
            assetState.countWarningEmitted = true;
          }
          continue;
        }
        assetState.count += 1;
        relPaths.push(rel.replace(/\\/g, '/'));
      }
    }
  }
  visitAssets(path.join(designDir, 'assets'), 'assets');
  const entries = await mapLimit(relPaths, 8, async relPath => {
    const filePath = path.join(designDir, relPath);
    return [relPath, await hashProjectFileAsync(filePath, relPath)];
  });
  const hashes = {};
  for (const [relPath, hash] of entries) hashes[relPath] = hash;
  return hashes;
}

async function validateMutation(designDir, report, errors, warnings) {
  const baseline = report.projectFileHashes;
  if (!baseline || typeof baseline !== 'object') {
    errors.push('validation-report.json missing projectFileHashes baseline');
    return;
  }

  const current = await collectProjectFileHashes(designDir, warnings);
  for (const [relPath, expectedHash] of Object.entries(baseline)) {
    if (!current[relPath]) {
      errors.push(`post-validation file missing: ${relPath}`);
    } else if (current[relPath] !== expectedHash) {
      errors.push(`post-validation mutation detected: ${relPath}`);
    }
  }
  for (const relPath of Object.keys(current)) {
    if (!Object.prototype.hasOwnProperty.call(baseline, relPath)) {
      errors.push(`post-validation file added: ${relPath}`);
    }
  }
}

function collectFiles(dir, prefix, predicate, options = {}) {
  const result = [];
  if (!fs.existsSync(dir)) return result;
  const maxDepth = Number.isInteger(options.maxDepth) ? options.maxDepth : Infinity;
  const maxEntries = Number.isInteger(options.maxEntries) ? options.maxEntries : Infinity;
  const state = options.state || createAssetTraversalState(options.warnings, options.warningLabel || 'artifact-readiness');

  function visit(currentDir, currentPrefix, depth) {
    if (depth > maxDepth) {
      if (!state.depthWarningEmitted) {
        warnAssetTraversal(state, `${prefix}/ traversal exceeded max depth ${maxDepth}; deeper files skipped`);
        state.depthWarningEmitted = true;
      }
      return;
    }
    for (const entry of fs.readdirSync(currentDir, { withFileTypes: true })) {
      const rel = path.join(currentPrefix, entry.name).replace(/\\/g, '/');
      const full = path.join(currentDir, entry.name);
      if (entry.isDirectory()) {
        visit(full, rel, depth + 1);
      } else if (entry.isFile() && predicate(entry.name, full, rel)) {
        if (state.count >= maxEntries) {
          if (!state.countWarningEmitted) {
            warnAssetTraversal(state, `${prefix}/ traversal reached max file count ${maxEntries}; remaining files skipped`);
            state.countWarningEmitted = true;
          }
          continue;
        }
        state.count += 1;
        result.push(rel);
      }
    }
  }
  visit(dir, prefix, 0);
  return result;
}

async function validateDesignArtifactReadiness(designDir, errors, warnings) {
  const designFiles = fs.readdirSync(designDir).filter(file => file.endsWith('.design'));
  if (designFiles.length === 0) {
    errors.push('No .design file found in design project root');
    return null;
  }
  if (designFiles.length > 1) {
    warnings.push(`Multiple .design files found: ${designFiles.join(', ')}`);
  }

  const pageFiles = new Set(
    collectFiles(path.join(designDir, 'pages'), 'pages', name => name.endsWith('.html'))
  );
  const assetFiles = new Set(
    collectFiles(
      path.join(designDir, 'assets'),
      'assets',
        (name, _full, rel) => HASH_IMAGE_EXTENSIONS.has(path.extname(name).toLowerCase()) && !rel.startsWith('assets/icons/'),
        {
          maxDepth: MAX_PROJECT_HASH_ASSET_DEPTH,
          maxEntries: MAX_PROJECT_HASH_ASSET_ENTRIES,
          warnings,
          warningLabel: 'artifact-readiness',
        }
    )
  );
  const registeredPages = new Set();
  const registeredImages = new Set();
  const pageIds = new Set();
  const pageNodes = [];

  for (const designFile of designFiles) {
    const designPath = path.join(designDir, designFile);
    let parsed;
    try {
      parsed = readJson(designPath);
    } catch (error) {
      errors.push(`${designFile}: failed to parse JSON: ${error.message}`);
      continue;
    }

    if (!Array.isArray(parsed.data) || parsed.data.length === 0) {
      errors.push(`${designFile}: data must be a non-empty array`);
      continue;
    }

    for (const [index, node] of parsed.data.entries()) {
      if (!node || typeof node !== 'object') continue;
      if (node.type === 'page') {
        pageNodes.push({ node, designFile, index });
        pageIds.add(node.id);
      }
    }
  }

  const pageHtmlChecks = [];
  for (const { node, designFile, index } of pageNodes) {
    const htmlSrc = node?.devMetadata?.htmlSrc;
    if (typeof htmlSrc !== 'string' || !htmlSrc) {
      errors.push(`${designFile}: data[${index}].devMetadata.htmlSrc is required`);
      continue;
    }
    const normalized = htmlSrc.replace(/\\/g, '/');
    registeredPages.add(normalized);
    pageHtmlChecks.push({
      node,
      designFile,
      index,
      normalized,
      htmlPath: path.join(designDir, normalized),
    });
  }

  const uniqueHtmlChecks = [...new Map(pageHtmlChecks.map(check => [check.htmlPath, check])).values()];
  const htmlByPath = new Map(
    await Promise.all(uniqueHtmlChecks.map(async check => {
      try {
        return [check.htmlPath, { html: await fs.promises.readFile(check.htmlPath, 'utf8') }];
      } catch (error) {
        if (error && error.code === 'ENOENT') return [check.htmlPath, { missing: true }];
        return [check.htmlPath, { error }];
      }
    }))
  );

  for (const { node, designFile, index, normalized, htmlPath } of pageHtmlChecks) {
    const htmlResult = htmlByPath.get(htmlPath) || {};
    let html = null;
    if (htmlResult.missing) {
      errors.push(`${designFile}: page node "${node.id}" htmlSrc missing on disk: ${normalized}`);
    } else if (htmlResult.error) {
      errors.push(`${designFile}: failed to read page node "${node.id}" htmlSrc ${normalized}: ${htmlResult.error.message}`);
    } else {
      html = htmlResult.html;
    }

    const interactions = node?.devMetadata?.interactions;
    if (interactions !== undefined && !Array.isArray(interactions)) {
      errors.push(`${designFile}: page node "${node.id}" interactions must be an array`);
    } else if (Array.isArray(interactions)) {
      for (const [interactionIndex, interaction] of interactions.entries()) {
        if (!interaction || typeof interaction !== 'object') {
          errors.push(`${designFile}: ${node.id}.interactions[${interactionIndex}] must be an object`);
          continue;
        }
        if (!interaction.domId) {
          errors.push(`${designFile}: ${node.id}.interactions[${interactionIndex}].domId is required`);
        } else if (html !== null) {
          if (!html.includes(`data-dom-id="${interaction.domId}"`) && !html.includes(`data-dom-id='${interaction.domId}'`)) {
            errors.push(`${designFile}: interaction domId "${interaction.domId}" not found in ${normalized}`);
          }
        }
        if (!pageIds.has(interaction.targetPageId)) {
          errors.push(`${designFile}: interaction targetPageId "${interaction.targetPageId}" does not reference an existing page node`);
        }
      }
    }
  }

  for (const designFile of designFiles) {
    const designPath = path.join(designDir, designFile);
    let parsed;
    try {
      parsed = readJson(designPath);
    } catch {
      continue;
    }

    for (const [index, node] of (parsed.data || []).entries()) {
      if (!node || typeof node !== 'object' || node.type !== 'image') continue;
      const imageSrc = node?.devMetadata?.imageSrc;
      if (typeof imageSrc !== 'string' || !imageSrc) {
        errors.push(`${designFile}: data[${index}].devMetadata.imageSrc is required`);
        continue;
      }
      const normalized = imageSrc.replace(/\\/g, '/');
      registeredImages.add(normalized);
      if (!fs.existsSync(path.join(designDir, normalized))) {
        errors.push(`${designFile}: image node "${node.id}" imageSrc missing on disk: ${normalized}`);
      }
    }
  }

  for (const pageFile of pageFiles) {
    if (!registeredPages.has(pageFile)) {
      errors.push(`HTML page exists but is not registered in .design: ${pageFile}`);
    }
  }
  for (const assetFile of assetFiles) {
    if (!registeredImages.has(assetFile)) {
      errors.push(`image asset exists but is not registered in .design: ${assetFile}`);
    }
  }

  return {
    designFiles,
    registeredPages: [...registeredPages].sort(),
    registeredImages: [...registeredImages].sort(),
    pageFiles: [...pageFiles].sort(),
    assetFiles: [...assetFiles].sort(),
  };
}

function isDiagnosticHistoryRecord(item) {
  return item?.diagnosticOnly === true || item?.diagnosticClass === 'repair-ledger';
}

function validateRepairLedger(designDir, summary, errors, warnings) {
  const history = Array.isArray(summary?.project?.validationHistory)
    ? summary.project.validationHistory
    : [];
  const failed = history.filter(item =>
    item &&
    !isDiagnosticHistoryRecord(item) &&
    (item.success === false || Number(item.exitCode) === 1)
  );
  const ledger = Array.isArray(summary?.project?.validationRepairLedger)
    ? summary.project.validationRepairLedger
    : [];
  const diagnosticReports = Array.isArray(summary?.project?.ledgerDiagnosticReports)
    ? summary.project.ledgerDiagnosticReports
    : [];
  if (failed.length === 0) {
    if (ledger.length > 0) {
        warnings.push('validationRepairLedger[] exists but validationHistory[] contains no failed validation');
    }
    return;
  }
  if (ledger.length === 0) {
      warnings.push('validationRepairLedger[] is missing even though validationHistory[] contains failed validation');
    return;
  }
  if (ledger.length > 2) {
    warnings.push(`validationRepairLedger[] has ${ledger.length} entries; retry_or_repair_loop risk should be reviewed`);
  }
  function findHistoryRecord(reportPath, reportHash, predicate = null) {
    const normalizedPath = String(reportPath || '').trim();
    const normalizedHash = String(reportHash || '').trim();
    if (!normalizedPath || !normalizedHash) return null;
    return history.find(item =>
      item &&
      String(item.reportPath || '').trim() === normalizedPath &&
      String(item.reportHash || '').trim() === normalizedHash &&
      (!predicate || predicate(item))
    ) || null;
  }
  function isFailedHistoryRecord(item) {
    return item && (item.success === false || Number(item.exitCode) === 1);
  }
  function findDiagnosticRecord(reportPath, reportHash) {
    const normalizedPath = String(reportPath || '').trim();
    const normalizedHash = String(reportHash || '').trim();
    if (!normalizedPath || !normalizedHash) return null;
    return diagnosticReports.find(item =>
      item &&
      item.diagnosticClass === 'repair-ledger' &&
      String(item.reportPath || '').trim() === normalizedPath &&
      String(item.reportHash || '').trim() === normalizedHash
    ) || null;
  }

  for (const [index, item] of ledger.entries()) {
      if (!item.repairWorkflowReadPath) warnings.push(`validationRepairLedger[${index}].repairWorkflowReadPath is missing`);
    if (!Array.isArray(item.ownerTriage) || item.ownerTriage.length === 0) {
        warnings.push(`validationRepairLedger[${index}].ownerTriage[] is missing`);
    }
    if (!Array.isArray(item.repairActions) || item.repairActions.length === 0) {
        warnings.push(`validationRepairLedger[${index}].repairActions[] is missing`);
    } else {
      for (const [actionIndex, action] of item.repairActions.entries()) {
        if (!Array.isArray(action?.preEditFileHashes) || action.preEditFileHashes.length === 0) {
            warnings.push(`validationRepairLedger[${index}].repairActions[${actionIndex}].preEditFileHashes[] is missing (legacy optional evidence)`);
        }
        if (!Array.isArray(action?.postEditFileHashes) || action.postEditFileHashes.length === 0) {
            warnings.push(`validationRepairLedger[${index}].repairActions[${actionIndex}].postEditFileHashes[] is missing (legacy optional evidence)`);
        }
        if (!Array.isArray(action?.repairOwnedFields) || action.repairOwnedFields.length === 0) {
            warnings.push(`validationRepairLedger[${index}].repairActions[${actionIndex}].repairOwnedFields[] is missing`);
        }
      }
    }
      if (!item.failedReportHash) warnings.push(`validationRepairLedger[${index}].failedReportHash is missing`);
      if (!item.revalidationReportPath) warnings.push(`validationRepairLedger[${index}].revalidationReportPath is missing`);
      if (!item.revalidationReportHash) warnings.push(`validationRepairLedger[${index}].revalidationReportHash is missing`);

    const failedReportPath = resolveInsideDesignDir(designDir, item.failedReportPath, errors, `validationRepairLedger[${index}].failedReportPath`);
    const failedReportRel = String(item.failedReportPath || '').trim();
    const revalidationReportRel = String(item.revalidationReportPath || '').trim();
    const failedHistory = findHistoryRecord(failedReportRel, item.failedReportHash, isFailedHistoryRecord);
    if (item.failedReportHash && !failedHistory) {
        warnings.push(`validationRepairLedger[${index}].failedReportHash does not reference a failed validationHistory record`);
    }
    const failedReportCanStillBeHashed = failedReportRel && failedReportRel !== revalidationReportRel;
    if (failedReportCanStillBeHashed && failedReportPath && fs.existsSync(failedReportPath) && item.failedReportHash && sha256File(failedReportPath) !== item.failedReportHash) {
      if (!failedHistory) errors.push(`validationRepairLedger[${index}].failedReportHash does not match ${item.failedReportPath}`);
    }

    const revalidationReportPath = resolveInsideDesignDir(designDir, item.revalidationReportPath, errors, `validationRepairLedger[${index}].revalidationReportPath`);
    const revalidationHistory = findHistoryRecord(revalidationReportRel, item.revalidationReportHash);
    const revalidationDiagnostic = findDiagnosticRecord(revalidationReportRel, item.revalidationReportHash);
    if (revalidationReportPath && fs.existsSync(revalidationReportPath)) {
      const currentHash = item.revalidationReportHash ? sha256File(revalidationReportPath) : null;
      const currentHashMatches = currentHash && currentHash === item.revalidationReportHash;
      if (item.revalidationReportHash && !currentHashMatches && !revalidationHistory && !revalidationDiagnostic) {
          warnings.push(`validationRepairLedger[${index}].revalidationReportHash does not match ${item.revalidationReportPath}`);
      }
      if (!item.revalidationReportHash || currentHashMatches) {
        try {
          const revalidationReport = readJson(revalidationReportPath);
          if (item.revalidationSuccess !== revalidationReport.success) {
            errors.push(`validationRepairLedger[${index}].revalidationSuccess=${item.revalidationSuccess} but ${item.revalidationReportPath}.success=${revalidationReport.success}`);
          }
        } catch (error) {
          errors.push(`validationRepairLedger[${index}].revalidationReportPath is unreadable JSON: ${error.message}`);
        }
      } else if (revalidationHistory && item.revalidationSuccess !== revalidationHistory.success) {
        errors.push(`validationRepairLedger[${index}].revalidationSuccess=${item.revalidationSuccess} but validationHistory report success=${revalidationHistory.success}`);
      } else if (revalidationDiagnostic && item.revalidationSuccess !== revalidationDiagnostic.success) {
        errors.push(`validationRepairLedger[${index}].revalidationSuccess=${item.revalidationSuccess} but ledgerDiagnosticReports report success=${revalidationDiagnostic.success}`);
      }
    } else if (item.revalidationReportPath && revalidationHistory && item.revalidationSuccess !== revalidationHistory.success) {
      errors.push(`validationRepairLedger[${index}].revalidationSuccess=${item.revalidationSuccess} but validationHistory report success=${revalidationHistory.success}`);
    } else if (item.revalidationReportPath && revalidationDiagnostic && item.revalidationSuccess !== revalidationDiagnostic.success) {
      errors.push(`validationRepairLedger[${index}].revalidationSuccess=${item.revalidationSuccess} but ledgerDiagnosticReports report success=${revalidationDiagnostic.success}`);
    } else if (item.revalidationReportPath && !revalidationHistory) {
      if (!revalidationDiagnostic) errors.push(`validationRepairLedger[${index}].revalidationReportPath not found: ${item.revalidationReportPath}`);
    }
  }

  const repairEntryEvidence = Array.isArray(summary?.project?.repairEntryEvidence)
    ? summary.project.repairEntryEvidence
    : [];
  if (repairEntryEvidence.length < failed.length) {
      warnings.push(`validationHistory has ${failed.length} failed validation(s) but repairEntryEvidence has ${repairEntryEvidence.length} entr${repairEntryEvidence.length === 1 ? 'y' : 'ies'}`);
  }

  for (const [failedIndex, failedRecord] of failed.entries()) {
    const failedTime = Date.parse(failedRecord.checkedAt || failedRecord.recordedAt || '');
    const failedReportPath = String(failedRecord.reportPath || '').trim();
    const failedReportHash = String(failedRecord.reportHash || '').trim();
    let matchingLedger = null;
    if (failedReportPath && failedReportHash) {
      matchingLedger = ledger.find(item => item && item.failedReportPath === failedReportPath && item.failedReportHash === failedReportHash) || null;
      if (!matchingLedger) {
          warnings.push(`validationHistory[${failedIndex}] has no matching validationRepairLedger entry for ${failedReportPath}#${failedReportHash}`);
        continue;
      }
    } else if (failedReportPath) {
      matchingLedger = ledger.find(item => item && item.failedReportPath === failedReportPath) || ledger[failedIndex];
    } else {
      matchingLedger = ledger[failedIndex];
    }
    if (!matchingLedger) continue;
    const repairTime = Date.parse(matchingLedger.repairStartedAt || matchingLedger.recordedAt || matchingLedger.timestamp || '');
    if (Number.isFinite(failedTime) && Number.isFinite(repairTime) && repairTime <= failedTime) {
        warnings.push(`validationRepairLedger[${failedIndex}].repairStartedAt should be later than failed validation checkedAt`);
    }
  }
}

function validateValidationEvidenceNotCleared(report, summary, errors) {
  const status = report?.validationRunDisciplineStatus;
  if (!status || typeof status !== 'object') return;
  const project = summary?.project || {};
  const history = Array.isArray(project.validationHistory) ? project.validationHistory : [];
  const countedHistory = history.filter(item => !isDiagnosticHistoryRecord(item));
  const ledger = Array.isArray(project.validationRepairLedger) ? project.validationRepairLedger : [];
  const expectedHistoryCount = Number(status.validationHistoryCount);
  const expectedLedgerCount = Number(status.repairLedgerCount);
  if (Number.isFinite(expectedHistoryCount) && countedHistory.length < expectedHistoryCount) {
    errors.push(`validationHistory[] was reduced after validation report was written: report=${expectedHistoryCount}, summary=${countedHistory.length}`);
  }
  if (Number.isFinite(expectedLedgerCount) && ledger.length < expectedLedgerCount) {
    errors.push(`validationRepairLedger[] was reduced after validation report was written: report=${expectedLedgerCount}, summary=${ledger.length}`);
  }
}

function isRestoreSummary(summary) {
  const project = summary?.project || {};
  const intent = project.intentProfile || {};
  return intent.caseFamily === 'restore_1to1' ||
    project.resolvedLane === 'restore_1to1' ||
    project.replicationMode === 'high-fidelity';
}

function validateRestoreFinalGate(summary, errors) {
  const project = summary?.project || {};
  if (!isRestoreSummary(summary)) return null;

  const pageStateLock = project.pageStateLock;
  if (!pageStateLock || typeof pageStateLock !== 'object') {
    errors.push('project.pageStateLock is required for restore final readiness');
  } else {
    if (!String(pageStateLock.currentState || '').trim()) {
      errors.push('project.pageStateLock.currentState is required for restore final readiness');
    }
    if (!Array.isArray(pageStateLock.forbiddenDeviations) || pageStateLock.forbiddenDeviations.length === 0) {
      errors.push('project.pageStateLock.forbiddenDeviations[] is required for restore final readiness');
    }
  }

  const checkpoints = Array.isArray(project.restoreVisualCheckpoints) ? project.restoreVisualCheckpoints : [];
  const highCheckpoints = checkpoints.filter(checkpoint => checkpoint && checkpoint.priority === 'high');
  if (highCheckpoints.length < 5) {
    errors.push(`restore final readiness requires >= 5 high-priority restoreVisualCheckpoints; found ${highCheckpoints.length}`);
  }
  for (const [index, checkpoint] of checkpoints.entries()) {
    if (!checkpoint || checkpoint.priority !== 'high') continue;
    if (!String(checkpoint.sourceFact || checkpoint.sourceObservation || '').trim()) {
      errors.push(`restoreVisualCheckpoints[${index}] high-priority row requires sourceFact or sourceObservation before final delivery`);
    }
    if (!String(checkpoint.expected || checkpoint.targetImplementation || '').trim()) {
      errors.push(`restoreVisualCheckpoints[${index}] high-priority row requires expected or targetImplementation before final delivery`);
    }
  }

  return {
    pageStateLockPresent: Boolean(pageStateLock && typeof pageStateLock === 'object'),
    highPriorityCheckpointCount: highCheckpoints.length,
    checkedAt: new Date().toISOString(),
  };
}

function validateFinalResponseText(finalResponseFile, errors, warnings) {
  if (!finalResponseFile) {
    errors.push('--final-response-file is required for restore delivery text policy');
    return null;
  }
  const resolved = path.resolve(finalResponseFile);
  if (!fs.existsSync(resolved)) {
    errors.push(`final response draft not found: ${resolved}`);
    return null;
  }
  const text = fs.readFileSync(resolved, 'utf8');
  const normalized = text.trim().replace(/\r\n/g, '\n');
  if (!normalized) {
    errors.push('final response draft is empty');
  }
  if (/\[[^\]]+\]\([^)]+\)/.test(normalized)) {
    errors.push('final response must not contain Markdown links');
  }
  if (/(?:computer|file):\/\//i.test(normalized)) {
    errors.push('final response must not contain computer:// or file:// URLs');
  }
  if (/(^|[\s([{`'"])(?:\/Users\/|\/var\/|\/tmp\/|[A-Za-z]:\\)[^\s)`'"]+/m.test(normalized)) {
    errors.push('final response must not contain bare local filesystem paths');
  }
  if (/\b(?:pages\/[^\s)`'"]+\.html|assets\/[^\s)`'"]+|[^\/\s)`'"]+\.design)\b/i.test(normalized)) {
    errors.push('final response must not contain manual artifact file references');
  }
  if (/查看(?:设计项目|页面|产物)|打开(?:设计项目|页面|产物)/.test(normalized)) {
    warnings.push('final response uses manual viewing language; prefer a short completion summary without artifact-link wording');
  }
  return {
    finalResponseFile: resolved,
    draftHash: hashString(normalized),
    characterCount: normalized.length,
    checkedAt: new Date().toISOString(),
  };
}

async function main() {
  const { designDir, check, finalResponseFile, errors: argErrors, warnings } = parseArgs(process.argv.slice(2));
  if (argErrors.length > 0) {
    for (const error of argErrors) console.error(`[ERROR] ${error}`);
    process.exit(1);
  }

  const errors = [];
  const reportPath = path.join(designDir, 'validation-report.json');
  const summaryPath = path.join(designDir, 'runtime-orchestration-summary.json');
  const hasReport = fs.existsSync(reportPath);
  const hasSummary = fs.existsSync(summaryPath);
  let report = null;
  let summary = null;

  if (hasSummary) {
    try {
      summary = readJson(summaryPath);
    } catch (error) {
      errors.push(`runtime-orchestration-summary.json is invalid JSON: ${error.message}`);
    }
  }
  else warnings.push('runtime-orchestration-summary.json not found; repair ledger checks skipped');

  const isRestore = isRestoreSummary(summary);

  if (!hasReport && !isRestore) errors.push('validation-report.json is required');
  else if (hasReport) {
    try {
      report = readJson(reportPath);
    } catch (error) {
      errors.push(`validation-report.json is invalid JSON: ${error.message}`);
    }
  }

  let artifact = null;
  let finalResponseEvidence = null;
  let restoreFinalGateEvidence = null;
  if (errors.length === 0) {
    if (report) {
      if (check !== 'repair-ledger') {
        validateReportSkillFreshness(report, errors);
        validateReportIntegrity(report, designDir, errors);
      }
      if (check !== 'repair-ledger' && report.success !== true) errors.push('validation-report.json success must be true');
      if ((check === 'all' || check === 'mutation') && report) await validateMutation(designDir, report, errors, warnings);
    }
    if (check === 'all' || check === 'readiness' || check === 'artifact') {
      artifact = await validateDesignArtifactReadiness(designDir, errors, warnings);
    }
    if ((check === 'all' || check === 'repair-ledger') && summary && report) {
      validateValidationEvidenceNotCleared(report, summary, errors);
      validateRepairLedger(designDir, summary, errors, warnings);
    }
    if (check === 'all' && summary && isRestore) {
      restoreFinalGateEvidence = validateRestoreFinalGate(summary, errors);
    }
    if (
      check === 'response' ||
      finalResponseFile ||
      (check === 'all' && summary && isRestore)
    ) {
      finalResponseEvidence = validateFinalResponseText(finalResponseFile, errors, warnings);
    }
  }

  const result = {
    success: errors.length === 0,
    check,
    errors,
    warnings,
    artifact,
    restoreFinalGateEvidence,
    finalResponseEvidence,
  };
  console.log(JSON.stringify(result, null, 2));
  process.exit(result.success ? 0 : 1);
}

main().catch(error => {
  console.error(`[ERROR] ${error.message}`);
  process.exit(1);
});
